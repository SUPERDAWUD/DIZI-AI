def _as_bool(value, default: bool = True) -> bool:
    if value is None:
        return default
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in {"1", "true", "yes", "on"}


def _pipeline_payload(final_output, image_url=None, profile=None) -> dict:
    if final_output is None:
        final_output = "No output generated by agents."

    final_output = str(final_output).strip()
    if not final_output:
        final_output = "No output generated by agents."

    if image_url is not None:
        image_url = str(image_url).strip() or None

    if not isinstance(profile, dict):
        profile = {}

    return {
        "output": final_output,
        "image_url": image_url,
        "profile": profile,
    }


@app.route("/api/stream")
def stream_events():
    def event_generator():
        q: queue.Queue = queue.Queue(maxsize=100)

        def publish(event: dict) -> None:
            try:
                q.put_nowait(event)
            except queue.Full:
                pass

        logger.subscribe(publish)
        try:
            while True:
                try:
                    event = q.get(timeout=15)
                    yield f"data: {json.dumps(event)}\n\n"
                except queue.Empty:
                    yield ": heartbeat\n\n"
        except GeneratorExit:
            return
        finally:
            logger.unsubscribe(publish)

    return Response(stream_with_context(event_generator()), mimetype="text/event-stream")

