@app.route("/api/kv-cache", methods=["GET"])
def get_kv_cache():
    if recent_runs:
        kv_cache = recent_runs[-1].get("kv_cache", {})
        if hasattr(kv_cache, "__dict__"):
            kv_cache = kv_cache.__dict__
        return jsonify({"kv_cache": kv_cache})
    return jsonify({"kv_cache": {}})

@app.route("/api/recent-runs", methods=["GET"])
def recent_runs_api():
    # Return summaries only (not full results to reduce payload)
    summaries = [
        {
            "timestamp": r["timestamp"],
            "filepath": r["filepath"],
            "use_fake_hardware": r["use_fake_hardware"],
            "has_results": "result" in r
        }
        for r in recent_runs
    ]
    return jsonify({"runs": summaries})

